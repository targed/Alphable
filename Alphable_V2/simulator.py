# Standard Scrabble letter values
LETTER_VALUES = {
    'A': 1, 'B': 3, 'C': 3, 'D': 2, 'E': 1, 'F': 4, 'G': 2, 'H': 4,
    'I': 1, 'J': 8, 'K': 5, 'L': 1, 'M': 3, 'N': 1, 'O': 1, 'P': 3,
    'Q': 10, 'R': 1, 'S': 1, 'T': 1, 'U': 1, 'V': 4, 'W': 4, 'X': 8,
    'Y': 4, 'Z': 10, '.': 0, '?': 0
}

# Standard Scrabble Premium Squares
# DW: Double Word, TW: Triple Word, DL: Double Letter, TL: Triple Letter
PREMIUM_SQUARES = {
    (0, 0): 'TW', (0, 7): 'TW', (0, 14): 'TW',
    (7, 0): 'TW', (7, 14): 'TW', (14, 0): 'TW', (14, 7): 'TW', (14, 14): 'TW',
    (1, 1): 'DW', (2, 2): 'DW', (3, 3): 'DW', (4, 4): 'DW',
    (10, 10): 'DW', (11, 11): 'DW', (12, 12): 'DW', (13, 13): 'DW',
    (1, 13): 'DW', (2, 12): 'DW', (3, 11): 'DW', (4, 10): 'DW',
    (10, 4): 'DW', (11, 3): 'DW', (12, 2): 'DW', (13, 1): 'DW',
    (7, 7): 'DW',  # Center square
    (1, 5): 'TL', (1, 9): 'TL', (5, 1): 'TL', (5, 5): 'TL',
    (5, 9): 'TL', (5, 13): 'TL', (9, 1): 'TL', (9, 5): 'TL',
    (9, 9): 'TL', (9, 13): 'TL', (13, 5): 'TL', (13, 9): 'TL',
    (0, 3): 'DL', (0, 11): 'DL', (2, 6): 'DL', (2, 8): 'DL',
    (3, 0): 'DL', (3, 7): 'DL', (3, 14): 'DL', (6, 2): 'DL',
    (6, 6): 'DL', (6, 8): 'DL', (6, 12): 'DL', (7, 3): 'DL',
    (7, 11): 'DL', (8, 2): 'DL', (8, 6): 'DL', (8, 8): 'DL',
    (8, 12): 'DL', (11, 0): 'DL', (11, 7): 'DL', (11, 14): 'DL',
    (12, 6): 'DL', (12, 8): 'DL', (14, 3): 'DL', (14, 11): 'DL'
}

def _calculate_move_points(board, move, rack_counts):
    """
    Internal fast path to calculate points for a move without copying the board.
    Takes rack_counts as a dictionary to avoid re-creation.
    """
    r, c = move['row'], move['col']
    word = move['word']
    direction = move['dir']

    points = 0
    word_multiplier = 1
    tiles_played = 0

    # Temporary copy of rack_counts for this move
    counts = rack_counts.copy()

    for i, char in enumerate(word):
        curr_r = r + (i if direction == 'Down' else 0)
        curr_c = c + (i if direction == 'Across' else 0)

        # Check if the square is empty
        if board[curr_r][curr_c] == '.':
            tiles_played += 1

            # Determine if we use a normal letter or a blank
            is_blank = False
            if counts.get(char, 0) > 0:
                counts[char] -= 1
            elif counts.get('?', 0) > 0:
                counts['?'] -= 1
                is_blank = True

            letter_val = 0 if is_blank else LETTER_VALUES.get(char, 0)

            # Premium squares only apply to newly placed tiles
            prem = PREMIUM_SQUARES.get((curr_r, curr_c), None)
            letter_multiplier = 1
            if prem == 'DL':
                letter_multiplier = 2
            elif prem == 'TL':
                letter_multiplier = 3
            elif prem == 'DW':
                word_multiplier *= 2
            elif prem == 'TW':
                word_multiplier *= 3

            points += letter_val * letter_multiplier
        else:
            # Tile is already on the board
            existing_char = board[curr_r][curr_c]
            is_blank = existing_char.islower()
            letter_val = 0 if is_blank else LETTER_VALUES.get(existing_char.upper(), 0)
            points += letter_val

    points *= word_multiplier
    if tiles_played == 7:
        points += 50
    return points


def find_best_greedy_move(board, moves, rack, return_simulation=False):
    """
    Finds the highest-scoring move from a list of legal moves.
    Optionally returns the full simulation of that move.
    """
    if not moves:
        return None

    rack_counts = {}
    for char in rack:
        rack_counts[char] = rack_counts.get(char, 0) + 1

    best_move = None
    max_points = -1

    for move in moves:
        points = _calculate_move_points(board, move, rack_counts)
        if points > max_points:
            max_points = points
            best_move = move

    if return_simulation:
        new_board, points, new_rack = simulate_move(board, best_move, rack)
        return {
            'move': best_move,
            'value': None,
            'new_board': new_board,
            'points': points,
            'new_rack': new_rack,
        }
    return best_move


def simulate_move(board, move, rack):
    """
    Applies a move to the board and calculates the new board state,
    the points scored, and the remaining rack.

    Args:
        board (list of list of str): 15x15 current board. '.' is empty.
                                     Lowercase letters are used for blanks already on board.
        move (dict): Move generated by GADDAG.
                     Format: {'row': int, 'col': int, 'dir': 'Across'|'Down', 'word': str}
                     Note: The 'word' from GADDAG in structure.pyx is just a string,
                     but doesn't inherently specify which letters were blanks.
                     For simulation, we will assume standard uppercase letters unless
                     we implement a blank-assignment heuristic.
        rack (list of str): The current rack. '?' for blank.

    Returns:
        new_board (list of list of str): The 15x15 board after the move.
        points (int): The points scored by the move.
        new_rack (list of str): The remaining rack after tiles are played.
    """
    new_board = [row[:] for row in board]
    rack_counts = {}
    for char in rack:
        rack_counts[char] = rack_counts.get(char, 0) + 1

    r, c = move['row'], move['col']
    word = move['word']
    direction = move['dir']

    points = 0
    word_multiplier = 1
    tiles_played = 0

    # We will track which characters were played from the rack to update it
    # We will try to play the actual letter first, then fall back to '?' (blank)
    placed_positions = []

    for i, char in enumerate(word):
        curr_r = r + (i if direction == 'Down' else 0)
        curr_c = c + (i if direction == 'Across' else 0)

        # Check if the square is empty
        if new_board[curr_r][curr_c] == '.':
            # We are placing a tile here
            tiles_played += 1
            placed_positions.append((curr_r, curr_c))

            # Determine if we use a normal letter or a blank
            is_blank = False
            if rack_counts.get(char, 0) > 0:
                rack_counts[char] -= 1
            elif rack_counts.get('?', 0) > 0:
                rack_counts['?'] -= 1
                is_blank = True
            else:
                # Fallback if the move is somehow invalid given the rack (shouldn't happen with correct generator)
                pass

            letter_val = 0 if is_blank else LETTER_VALUES.get(char, 0)

            # Place it on the board (lowercase if blank to differentiate on the board)
            new_board[curr_r][curr_c] = char.lower() if is_blank else char

            # Premium squares only apply to newly placed tiles
            prem = PREMIUM_SQUARES.get((curr_r, curr_c), None)
            letter_multiplier = 1
            if prem == 'DL':
                letter_multiplier = 2
            elif prem == 'TL':
                letter_multiplier = 3
            elif prem == 'DW':
                word_multiplier *= 2
            elif prem == 'TW':
                word_multiplier *= 3

            points += letter_val * letter_multiplier
        else:
            # Tile is already on the board
            existing_char = new_board[curr_r][curr_c]
            is_blank = existing_char.islower()
            letter_val = 0 if is_blank else LETTER_VALUES.get(existing_char.upper(), 0)
            points += letter_val

    points *= word_multiplier

    # Bingo bonus
    if tiles_played == 7:
        points += 50

    # Reconstruct the new rack
    new_rack = []
    for tile, count in rack_counts.items():
        if count > 0:
            new_rack.extend([tile] * count)

    # Note: A real Scrabble simulator would also calculate points for cross-words
    # created by the newly placed tiles. For the After-State Value network,
    # exact scoring is helpful but the board state itself is the most important output.
    # To keep this fast for Phase 1, we calculate the primary word score.

    return new_board, points, new_rack

# Helper to easily create a blank 15x15 board
def create_empty_board():
    return [['.' for _ in range(15)] for _ in range(15)]
