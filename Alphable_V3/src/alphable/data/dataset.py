import json
import torch
from torch.utils.data import Dataset, DataLoader
from alphable.core import inference

class AlphableDataset(Dataset):
    def __init__(self, jsonl_file):
        """
        Loads the compact dataset generated by prepare_dataset.py into memory.
        """
        self.samples = []
        with open(jsonl_file, 'r', encoding='utf-8') as f:
            for line in f:
                line_str = line.strip()
                if not line_str:
                    continue
                try:
                    self.samples.append(json.loads(line_str))
                except json.JSONDecodeError:
                    continue

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        """
        Expands the compact representation into [31, 15, 15] and [36] tensors on-the-fly.
        """
        sample = self.samples[idx]

        # 1. Expand Board
        compact_board = sample.get('board', '')
        if len(compact_board) < 225:
            compact_board = compact_board.ljust(225, '.')

        # Convert string to 15x15 list of lists
        board_2d = []
        for r in range(15):
            start_idx = r * 15
            end_idx = start_idx + 15
            row_str = compact_board[start_idx:end_idx]
            board_2d.append(list(row_str))

        board_tensor = inference.board_to_tensor(board_2d)

        # 2. Expand State
        rack_str = sample.get('rack', '')
        score_diff = float(sample.get('score_diff', 0.0))
        bag_remaining = int(sample.get('bag', 86))

        state_tensor = inference.state_to_tensor(list(rack_str), score_diff, bag_remaining)

        # 3. Target
        target_tensor = torch.tensor([sample.get('target', 0.0)], dtype=torch.float32)

        return board_tensor, state_tensor, target_tensor

def get_dataloaders(jsonl_file, batch_size=256, train_split=0.9):
    """
    Creates Training and Validation DataLoaders.
    """
    dataset = AlphableDataset(jsonl_file)

    total_size = len(dataset)
    train_size = int(total_size * train_split)
    val_size = total_size - train_size

    # Use fixed generator for reproducible splits
    generator = torch.Generator().manual_seed(42)
    train_dataset, val_dataset = torch.utils.data.random_split(dataset, [train_size, val_size], generator=generator)

    use_pin_memory = torch.cuda.is_available()
    train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True, num_workers=0, pin_memory=use_pin_memory)
    val_loader = DataLoader(val_dataset, batch_size=batch_size, shuffle=False, num_workers=0, pin_memory=use_pin_memory)

    return train_loader, val_loader
